(function expandSessionTerms(value){
  if(Array.isArray(value)){
    value.forEach((item,index)=>{
      if(typeof item==='string')value[index]=sessionTermReplacements.reduce((text,[pattern,replacement])=>text.replace(pattern,replacement),item);
      else expandSessionTerms(item);
    });
    return;
  }
  if(!value||typeof value!=='object')return;
  Object.keys(value).forEach(key=>{
    if(typeof value[key]==='string')value[key]=sessionTermReplacements.reduce((text,[pattern,replacement])=>text.replace(pattern,replacement),value[key]);
    else expandSessionTerms(value[key]);
  });
})(window.SESSION_DATA);
