const fs=require('fs'),vm=require('vm'),assert=require('assert'),path=require('path');
const read=p=>fs.readFileSync(path.join(__dirname,p),'utf8');
for(const p of ['assets/data.js','assets/app.js'])new vm.Script(read(p),{filename:p});
const context={window:{}};vm.createContext(context);vm.runInContext(read('assets/data.js'),context);
const d=context.window.SESSION_DATA;
assert.strictEqual(d.navigation.length,9,'9 navigation screens');
assert.strictEqual(d.dealflows.length,3,'3 business scenarios');
assert.strictEqual(d.cases.length,8,'8 source-based cases');
assert.strictEqual(d.companies.length,6,'6 holding entities');
assert.strictEqual(d.executives.filter(x=>x.super==='ceo').length,6,'6 CEO direct reports');
for(const f of d.dealflows){const notes=d.details.flows[f.id];assert.strictEqual(notes.length,f.steps.length,`details ${f.id}`);for(const stage of notes){assert(stage.process.length>70,'stage process');assert(stage.solution.length>25,'stage solution');}}
for(const dir of d.directions){assert(d.details.directions[dir.id].cases,'direction case references');}
for(const c of d.cases){assert(d.details.cases[c.id].process,'case process');}
const ui=read('assets/app.js');
const css=read('assets/style.css');
assert(ui.includes('requestFullscreen'),'fullscreen behavior');
assert(ui.includes("e.key==='PageDown'"),'presentation clicker');
assert(ui.includes('data-open-case'),'linked case navigation');
assert(ui.includes('branchSerial'),'organization updates without re-render');
assert(ui.includes('switchFlow'),'workflow changes without re-render');
assert(ui.includes('detailSerial'),'animated focus panel state');
assert(ui.includes('adaptDetailColumns'),'responsive case layout');
assert(ui.includes('zoomToDetail'),'zoom-to-case behavior');
assert(read('index.html').includes('id="detail-zoom"'),'focus overlay');
assert(read('index.html').includes('aria-describedby="detail-subtitle"'),'dialog description');
assert(ui.includes('detailLastFocus'),'dialog focus restoration');
assert(ui.includes('shell.inert=true'),'background isolation while dialog is open');
assert(ui.includes('window.innerWidth>620'),'mobile-safe dialog animation');
assert(ui.includes('el.dataset.item===`case:${dest}`'),'linked-case focus restoration');
assert(ui.includes("setInlineDetail('exec',id)"),'organization details remain inline');
assert(ui.includes("new Set(['direction','flow','case'])"),'dialogs are limited to business processes and cases');
assert(ui.includes('function setDetail(type,id,{expand=false}={})'),'cards update preview without opening a dialog');
assert(ui.includes('adaptInlineInspector'),'inline details adapt to viewport height');
assert(ui.includes("type!=='flow'"),'flow inspector fix');
assert(read('index.html').includes('id="fullscreen"'),'fullscreen button');
assert(css.includes('.org-overview-label'),'org hierarchy text layout');
assert(css.includes('@media(max-width:680px){.side{position:fixed}}'),'mobile menu remains an overlay');
assert(css.includes('height:min(760px,100%)'),'short-viewport dialog bounds');
assert(css.includes('.detail-lane .section{flex:1 1 auto'),'modal content fills available height');
assert(css.includes('.slide-grid.inline-focus'),'inline detail column expands after selection');
assert(css.includes('data-inline-density="4"'),'inline detail density has a no-scroll compact mode');
assert(read('index.html').includes('assets/navarro-logo.png'),'company logo is wired into the presentation');
assert(read('assets/app.js').includes('ПРЯМОЕ ПОДЧИНЕНИЕ CEO'),'exec hierarchy legend');
console.log(`PASS · NAVARRO Session v4.5: ${d.navigation.length} экранов, ${d.dealflows.reduce((n,f)=>n+f.steps.length,0)} этапа, ${d.cases.length} кейсов, адаптивная focus-колонка без внутренней прокрутки`);
